#!/usr/bin/env python3
"""Regenerate docs/evidence-template.md from expectations/controls.yml and the manual-steps index.

Usage: python3 scripts/gen_evidence_template.py           (rewrite after changing the catalogue)
       python3 scripts/gen_evidence_template.py --check   (read-only: exit 1 if the file is out of date)
"""
import os
import re
import sys

import yaml

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
LAYERS = {1: "1 Platform", 2: "2 Data", 3: "3 Models & Gateway", 4: "4 Genie", 5: "5 Agents, MCP & Search",
          6: "6 Cost", 7: "7 Audit"}
ORDER = "PDGFBAVTSXROC"

cat = yaml.safe_load(open(os.path.join(ROOT, "expectations", "controls.yml")))
manual = []
for line in open(os.path.join(ROOT, "docs", "manual-steps.md")):
    m = re.match(r"^\| (M-\d\d) \| (.+?) \| (.+?) \|$", line.strip())
    if m:
        manual.append(m.groups())


def expected(meta):
    exp = meta.get("expected") or {}
    if list(exp) == ["admin"]:
        return f"admin: {exp['admin']}"
    return "; ".join(f"{p}: {v}" for p, v in exp.items())


def key(tid):
    return (cat[tid].get("layer", 9), ORDER.index(tid[0]) if tid[0] in ORDER else 99, tid)


out = ["# GenAI governance lab: evidence and sign-off", "",
       "<!-- Generated by scripts/gen_evidence_template.py from expectations/controls.yml. Do not edit by hand. -->", "",
       "| | |", "|---|---|", "| Organisation | |", "| Workspace (name, region) | |", "| CSP enabled | yes / no |",
       "| Lab version (git commit) | |", "| Suite run ID (dashboard / export) | |", "| Date of run | |",
       "| Facilitator | |", "| Security reviewer | |", "",
       "Attach: `evidence/results-<date>.csv` (from `scripts/export_results.sh`, latest suite run only), "
       "`evidence/account_checks.json`, screenshots for manual steps.", "",
       "Result: PASS / FAIL / SKIP / MANUAL / INFO / PENDING / MISSING. Use the **INFO / note** column for INFO results "
       "(recorded, no verdict), SKIP reasons and findings such as B-05.", "",
       "## Automated tests", "",
       "| Layer | Test | Control | Expected (per persona) | Result | INFO / note | Evidence (file, screenshot) | Owner | Due |",
       "|---|---|---|---|---|---|---|---|---|"]
for tid in sorted(cat, key=key):
    meta = cat[tid]
    src = " (lab_evidence, next day)" if meta.get("source") == "evidence" else ""
    out.append(f"| {LAYERS.get(meta.get('layer'), meta.get('layer'))} | {tid} | {meta.get('title', '')}{src} | "
               f"{expected(meta).replace('|', '/')} | | | | | |")
out += ["", "## Manual steps ([manual-steps.md](manual-steps.md))", "",
        "| Step | Control | Who | Result | INFO / note | Evidence (file, screenshot) | Owner | Due |",
        "|---|---|---|---|---|---|---|---|"]
for mid, ctrl, who in manual:
    out.append(f"| {mid} | {ctrl} | {who} | | | | | |")
out += ["", "## Decisions recorded", "", "| Decision | Value agreed | Agreed by | Date |", "|---|---|---|---|",
        "| Partner-powered AI (on/off, enforced) | | | |", "| Geography enforcement per workspace | | | |",
        "| Data Classification (cross-Geo needed in Singapore) or manual class.sg_* tags | | | |",
        "| Genie file upload (on/off) | | | |", "| Agent mode (on/off, which workspaces) | | | |",
        "| Compliance Security Profile (on/off per workspace, standards) | | | |",
        "| Groups allowed to read PII in cleartext | | | |", "| Approved AI service builders (B-06) | | | |", "",
        "## Sign-off", "Reviewed by: ____________________  Date: __________", ""]
target = os.path.join(ROOT, "docs", "evidence-template.md")
text = "\n".join(out)
if "--check" in sys.argv[1:]:
    current = open(target).read() if os.path.exists(target) else ""
    if current != text:
        sys.exit("docs/evidence-template.md is out of date: run python3 scripts/gen_evidence_template.py")
    print(f"docs/evidence-template.md is up to date ({len(cat)} tests, {len(manual)} manual steps)")
else:
    open(target, "w").write(text)
    print(f"wrote docs/evidence-template.md ({len(cat)} tests, {len(manual)} manual steps)")
